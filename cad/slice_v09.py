"""Actual PrusaSlicer estimate of the separated, oriented 20-piece kit."""
from pathlib import Path
import json,subprocess,math,zipfile,hashlib
import trimesh
import analyze_slice as a
ROOT=Path(__file__).resolve().parents[1];OUT=ROOT/'exports/v09';RP=ROOT/'reports/v09';SL=ROOT.parent/'_support/tools/PrusaSlicer/PrusaSlicer-2.9.6/prusa-slicer-console.exe'
def run(args,log):
    args = [args[0], '--sw-renderer', '--datadir', str(ROOT.parent/'_support/config/PrusaSlicer'), '--threads', '2'] + list(args[1:])
    with (ROOT/'.tools'/log).open('w',encoding='utf8') as f:subprocess.run([str(x) for x in args],stdout=f,stderr=subprocess.STDOUT,check=True)
def summary(g):
    a.GCODE=g;_,_,_,lengths,footer=a.parse();factor=math.pi*(1.75/2)**2/1000*1.24
    mass={k:v*factor for k,v in lengths.items()}
    return dict(model_g=sum(v for k,v in mass.items() if not k.startswith('Support') and k!='Skirt/Brim'),support_g=sum(v for k,v in mass.items() if k.startswith('Support')),adhesion_g=mass.get('Skirt/Brim',0),total_g=float(footer['filament used [g]']),time=footer['estimated printing time (normal mode)'])
def main():
    import ctypes
    if hasattr(ctypes, 'windll'): ctypes.windll.kernel32.SetPriorityClass(ctypes.c_void_p(-1),0x4000)
    info=json.loads((RP/'cad_metrics.json').read_text(encoding='utf8'));ini=ROOT/'slicing/V0.9_PLA_0.4_0.20_ESTIMATE.ini'
    profile=(ROOT/'slicing/V0.6_PLA_0.4_0.20_ESTIMATE.ini').read_text().replace('V0.5 generic','V0.9 generic').replace('V0.6','V0.9')
    # Internal cartridge roof supports require support on existing model surfaces.
    profile=profile.replace('support_material_buildplate_only = 1','support_material_buildplate_only = 0')
    ini.write_text(profile,encoding='utf8');scene=trimesh.Scene();x=y=10;row_h=0;placements=[]
    for r in info['parts']:
        mesh=trimesh.load_mesh(ROOT/r['print_file']);w,h,_=mesh.extents
        if x+w>210:x=10;y+=row_h+12;row_h=0
        assert y+h<210,(r['name'],y+h)
        delta=[x-mesh.bounds[0][0],y-mesh.bounds[0][1],-mesh.bounds[0][2]];mesh.apply_translation(delta)
        scene.add_geometry(mesh,node_name=r['name']);placements.append(dict(name=r['name'],bounds=mesh.bounds.tolist()));x+=w+12;row_h=max(row_h,h)
    scene.units='mm';raw=ROOT/'.tools/V0.9_raw_plate.3mf';raw.write_bytes(trimesh.exchange.threemf.export_3MF(scene))
    plate=OUT/'quietmirror_V0.9_PRINT_PLATE.3mf'
    run([SL,'--load',ini,'--dont-arrange','--export-3mf','--output',plate,raw],'v09_export_plate.log')
    full=ROOT/'slicing/V0.9_PLA_0.4_0.20_FULL.ini';run([SL,'--load',ini,'--save',full],'v09_profile.log')
    # Store the full slicer configuration inside the actual 3MF, then slice it
    # without --load to verify the exported project carries its own settings.
    import xml.etree.ElementTree as ET
    with zipfile.ZipFile(plate) as z:files={n:z.read(n) for n in z.namelist()}
    config='; generated by PrusaSlicer 2.9.6; Quietmirror V0.9\n'+''.join('; '+line+'\n' for line in full.read_text(encoding='utf8').splitlines() if ' = ' in line and not line.startswith('#'))
    files['Metadata/Slic3r_PE.config']=config.encode('utf8')
    with zipfile.ZipFile(plate,'w',zipfile.ZIP_DEFLATED) as z:
        for n,b in files.items():z.writestr(n,b)
    g=ROOT/'.tools/V0.9_plate.gcode';run([SL,'--dont-arrange','--export-gcode','--output',g,plate],'v09_slice_plate.log')
    run([SL,'--info',plate],'v09_plate_info.log')
    text=(ROOT/'.tools/v09_plate_info.log').read_text();(RP/'slicer_model_info.txt').write_text(text,encoding='utf8')
    gtext=g.read_text(encoding='utf8');checks={}
    for key,value in [('nozzle_diameter','0.4'),('layer_height','0.2'),('perimeters','4'),('fill_density','20%'),('support_material_buildplate_only','0'),('filament_density','1.24'),('temperature','210'),('bed_temperature','60')]:
        checks[key]=f'; {key} = {value}\n' in gtext
    assert all(checks.values()),checks
    result=dict(version='0.9',slicer='PrusaSlicer 2.9.6',material='PLA estimate, density 1.24 g/cm3',profile=str(ini.relative_to(ROOT)),plate=str(plate.relative_to(ROOT)),units='mm',objects=len(placements),placements=placements,plate_estimate=summary(g),embedded_profile_checks=checks,validation='3MF sliced without an external --load profile. Separate parts, not the overlapping assembled inspection scene. Optional detent leaf included in PLA mass estimate; its spring feel/durability are not validated.')
    result['source_metrics_sha256']=hashlib.sha256((RP/'cad_metrics.json').read_bytes()).hexdigest()
    (RP/'slice_summary.json').write_text(json.dumps(result,indent=2),encoding='utf8');print(json.dumps(result['plate_estimate']),flush=True)
if __name__=='__main__':main()
