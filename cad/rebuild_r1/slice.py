"""Actually slice the separated R1 pieces; deliver embedded-profile 3MF, not G-code."""
from pathlib import Path
import ctypes, hashlib, json, math, os, subprocess, zipfile
import trimesh

HERE=Path(__file__).resolve().parent;ROOT=HERE.parents[1];SUP=ROOT.parent/'_support'
OUT=ROOT/'exports/rebuild_r1';RP=ROOT/'reports/rebuild_r1';WORK=SUP/'work/fenrir_rebuild/slice'
SL=SUP/'tools/PrusaSlicer/PrusaSlicer-2.9.6/prusa-slicer-console.exe'


def run(args,name):
    with (WORK/(name+'.log')).open('w',encoding='utf-8') as f:
        subprocess.run([str(SL),'--sw-renderer','--datadir',str(SUP/'config/PrusaSlicer'),'--threads','2',*map(str,args)],stdout=f,stderr=subprocess.STDOUT,check=True,timeout=900)


def main():
    try:ctypes.windll.kernel32.SetPriorityClass(ctypes.c_void_p(-1),0x4000)
    except Exception:pass
    WORK.mkdir(exist_ok=True,parents=True)
    metrics=json.loads((RP/'cad_metrics.json').read_text())
    profile=(ROOT/'slicing/V0.6_PLA_0.4_0.20_ESTIMATE.ini').read_text().replace('V0.5 generic','R1 generic').replace('V0.6','R1')
    profile=profile.replace('support_material_buildplate_only = 1','support_material_buildplate_only = 0')
    ini=HERE/'PLA_0.4_0.20_ESTIMATE.ini';ini.write_text(profile,encoding='utf-8',newline='\n')
    scene=trimesh.Scene();placements=[];x=y=10;row_h=0
    for n,m in metrics.items():
        if not m['printable']:continue
        mesh=trimesh.load_mesh(OUT/f'print/{n}.stl');w,h,_=mesh.extents
        if x+w>210:x=10;y+=row_h+12;row_h=0
        assert y+h<210,(n,'plate overflow')
        mesh.apply_translation([x-mesh.bounds[0,0],y-mesh.bounds[0,1],-mesh.bounds[0,2]])
        scene.add_geometry(mesh,node_name=n);placements.append({'part':n,'bounds':mesh.bounds.tolist()});x+=w+12;row_h=max(row_h,h)
    scene.units='mm';raw=WORK/'raw_plate.3mf';raw.write_bytes(trimesh.exchange.threemf.export_3MF(scene))
    plate=OUT/'FENRIR_MINISE_R1_PLA_PRINT_PLATE.3mf'
    run(['--load',ini,'--dont-arrange','--export-3mf','--output',plate,raw],'export')
    full=WORK/'full.ini';run(['--load',ini,'--save',full],'profile')
    with zipfile.ZipFile(plate) as z:files={n:z.read(n) for n in z.namelist()}
    config='; generated by PrusaSlicer 2.9.6; R1 generic PLA estimate\n'+''.join('; '+s+'\n' for s in full.read_text(encoding='utf-8').splitlines() if ' = ' in s and not s.startswith('#'))
    files['Metadata/Slic3r_PE.config']=config.encode('utf-8')
    with zipfile.ZipFile(plate,'w',zipfile.ZIP_DEFLATED) as z:
        for n,b in files.items():z.writestr(n,b)
    gcode=WORK/'R1_validation_only.gcode'
    run(['--dont-arrange','--export-gcode','--output',gcode,plate],'slice')
    run(['--info',plate],'info')
    text=gcode.read_text(encoding='utf-8');footer={}
    for line in text.splitlines():
        if line.startswith('; ') and ' = ' in line:
            key,val=line[2:].split(' = ',1);footer[key]=val
    required={'nozzle_diameter':'0.4','layer_height':'0.2','perimeters':'4','fill_density':'20%',
              'support_material_buildplate_only':'0','filament_density':'1.24','temperature':'210','bed_temperature':'60'}
    checks={k:footer.get(k)==v for k,v in required.items()}
    summary={'slicer':'PrusaSlicer 2.9.6','objects':len(placements),'placements':placements,
        'estimated_total_filament_g':footer.get('filament used [g]'),
        'estimated_time':footer.get('estimated printing time (normal mode)'),
        'embedded_profile_checks':checks,'pass':all(checks.values()),
        'plate':str(plate.relative_to(ROOT)),'plate_sha256':hashlib.sha256(plate.read_bytes()).hexdigest(),
        'scope':'Actual slice from embedded-profile 3MF without external --load. Generic PLA estimate, supports enabled; reslice for the actual printer. G-code retained only as E-drive validation evidence.',
        'source_metrics_sha256':hashlib.sha256((RP/'cad_metrics.json').read_bytes()).hexdigest()}
    (RP/'slice_summary.json').write_text(json.dumps(summary,indent=2)+'\n',encoding='utf-8',newline='\n')
    (RP/'slicer_model_info.txt').write_text((WORK/'info.log').read_text(encoding='utf-8'),encoding='utf-8',newline='\n')
    print(json.dumps(summary,indent=2));assert summary['pass']


if __name__=='__main__':main()
